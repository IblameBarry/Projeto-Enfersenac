CREATE COLLATION IF NOT EXISTS public.mysql_unicode_ci (
    provider = icu,
    locale = 'und-u-ks-level1',
    deterministic = false
);

DO $$ BEGIN
    CREATE TYPE public.historia_origem AS ENUM ('PROFESSOR', 'SISTEMA');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
    CREATE TYPE public.historia_status AS ENUM ('ATIVA', 'ARQUIVADA');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
    CREATE TYPE public.resposta_status AS ENUM ('RASCUNHO', 'ENVIADA');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

CREATE TABLE IF NOT EXISTS public.professor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 0 AND 4294967295),
    nome VARCHAR(120) COLLATE public.mysql_unicode_ci NOT NULL,
    email VARCHAR(160) COLLATE public.mysql_unicode_ci NOT NULL,
    senha_hash VARCHAR(255) COLLATE public.mysql_unicode_ci NOT NULL DEFAULT '$2b$10$tJcm/OFcHW3Z8vGu.4u7yeJDYks9d.fF9r7pzGskZ6BBp/BnNpMRK',
    foto_url VARCHAR(255) COLLATE public.mysql_unicode_ci,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    admin BOOLEAN NOT NULL DEFAULT FALSE,
    criado_em TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_professor_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS public.aluno (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 0 AND 4294967295),
    nome VARCHAR(120) COLLATE public.mysql_unicode_ci NOT NULL,
    turma VARCHAR(20) COLLATE public.mysql_unicode_ci NOT NULL,
    criado_em TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ultimo_acesso TIMESTAMP(0) WITHOUT TIME ZONE,
    CONSTRAINT uq_aluno_nome_turma UNIQUE (nome, turma)
);

CREATE TABLE IF NOT EXISTS public.historia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 0 AND 4294967295),
    codigo VARCHAR(20) COLLATE public.mysql_unicode_ci NOT NULL,
    titulo VARCHAR(150) COLLATE public.mysql_unicode_ci NOT NULL,
    enunciado TEXT COLLATE public.mysql_unicode_ci NOT NULL,
    origem public.historia_origem NOT NULL DEFAULT 'PROFESSOR',
    professor_id BIGINT,
    turma VARCHAR(20) COLLATE public.mysql_unicode_ci,
    data_publicacao TIMESTAMP(0) WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_expiracao DATE,
    status public.historia_status NOT NULL DEFAULT 'ATIVA',
    CONSTRAINT uq_historia_codigo UNIQUE (codigo),
    CONSTRAINT fk_historia_professor FOREIGN KEY (professor_id) REFERENCES public.professor(id),
    CONSTRAINT ck_historia_origem CHECK ((origem = 'PROFESSOR' AND professor_id IS NOT NULL) OR origem = 'SISTEMA')
);
CREATE INDEX IF NOT EXISTS ix_historia_professor ON public.historia (professor_id);
CREATE INDEX IF NOT EXISTS ix_historia_turma ON public.historia (turma, status);

